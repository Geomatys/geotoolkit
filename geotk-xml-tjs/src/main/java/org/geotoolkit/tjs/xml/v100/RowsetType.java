package org.geotoolkit.tjs.xml.v100;

import java.util.ArrayList;
import java.util.List;
import jakarta.xml.bind.annotation.XmlAccessType;
import jakarta.xml.bind.annotation.XmlAccessorType;
import jakarta.xml.bind.annotation.XmlElement;
import jakarta.xml.bind.annotation.XmlType;

/**
 * Dataset table with columns as defined in the {@code Columnset} structure.
 *
 * @author Quentin Bialota (Geomatys)
 */
@XmlAccessorType(XmlAccessType.FIELD)
@XmlType(name = "RowsetType", propOrder = {"row"})
public class RowsetType {

    @XmlElement(name = "Row", required = true)
    private List<RowType> row;

    public List<RowType> getRow() {
        if (row == null) {
            row = new ArrayList<>();
        }
        return row;
    }

    public void setRow(List<RowType> row) {
        this.row = row;
    }
}
