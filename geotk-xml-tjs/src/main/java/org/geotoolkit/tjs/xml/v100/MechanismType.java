package org.geotoolkit.tjs.xml.v100;

import jakarta.xml.bind.annotation.XmlAccessType;
import jakarta.xml.bind.annotation.XmlAccessorType;
import jakarta.xml.bind.annotation.XmlElement;
import jakarta.xml.bind.annotation.XmlType;

/**
 * Mechanism by which the attribute data can be accessed once it has been joined to the spatial framework.
 *
 * @author Quentin Bialota (Geomatys)
 */
@XmlAccessorType(XmlAccessType.FIELD)
@XmlType(name = "MechanismType", propOrder = {"identifier", "title", "abstractText", "reference"})
public class MechanismType {

    @XmlElement(name = "Identifier", required = true)
    private String identifier;

    @XmlElement(name = "Title", required = true)
    private String title;

    @XmlElement(name = "Abstract", required = true)
    private String abstractText;

    @XmlElement(name = "Reference", required = true)
    private String reference;

    public String getIdentifier() {
        return identifier;
    }

    public void setIdentifier(String identifier) {
        this.identifier = identifier;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getAbstractText() {
        return abstractText;
    }

    public void setAbstractText(String abstractText) {
        this.abstractText = abstractText;
    }

    public String getReference() {
        return reference;
    }

    public void setReference(String reference) {
        this.reference = reference;
    }
}
